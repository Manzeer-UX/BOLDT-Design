const { chromium, expect } = require('playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');

(async () => {
  const output = path.join(os.tmpdir(), 'boldt-live-preview');
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => /^https?:\/\/(localhost|127\.0\.0\.1)(:|\/)/.test(route.request().url()) ? route.continue() : route.abort());
    await page.goto('http://localhost:5173/');
    await page.locator('input[type=email]').fill('preview@example.com');
    await page.locator('#password').fill('preview-only');
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await page.getByRole('tab', { name: 'Live Data' }).click();
    await expect(page.locator('.ld-table tbody tr')).toHaveCount(1);
    const video = page.locator('.ld-video-player');
    await page.waitForFunction(() => document.querySelector('.ld-video-player')?.readyState >= 2);
    assert.ok(await video.evaluate(element => element.duration >= 19 && element.duration < 20));
    await page.locator('.ld-interval').first().click();
    await expect.poll(() => video.evaluate(element => element.currentTime)).toBeCloseTo(6.66, 1);
    await video.evaluate(element => element.play());
    await expect.poll(() => video.evaluate(element => element.currentTime)).toBeGreaterThan(7.5);
    await video.evaluate(element => element.pause());
    assert.ok(await video.evaluate(element => {
      const canvas = document.createElement('canvas'); canvas.width = 64; canvas.height = 36;
      const context = canvas.getContext('2d'); context.drawImage(element, 0, 0, 64, 36);
      return new Set(context.getImageData(0, 0, 64, 36).data).size > 20;
    }), 'Video must display decoded image pixels');
    await expect(page.locator('.ld-video-playhead')).toBeVisible();
    await expect(page.locator('.ld-progress')).toContainText('0 / 400');
    await page.getByLabel('Live data zone', { exact: true }).selectOption('zones');
    await expect(page.locator('.ld-table tbody tr')).toHaveCount(4);
    await expect(page.locator('.ld-lane')).toHaveCount(2);
    await page.getByLabel('Live data zone', { exact: true }).selectOption({ label: 'Zone 1' });
    await expect(page.locator('.ld-table tbody tr')).toHaveCount(3);
    await expect(page.locator('.ld-progress')).toContainText('0 / 200');
    await page.getByLabel('Zoom in timeline', { exact: true }).click();
    await expect(page.getByRole('slider', { name: 'Timeline position' })).toBeVisible();
    await page.getByLabel('Reset timeline', { exact: true }).click();
    await expect(page.getByRole('slider', { name: 'Timeline position' })).toHaveCount(0);
    await page.locator('.ld-evidence-link').first().click();
    await expect(page.getByRole('dialog')).toBeVisible();
    const firstImage = await page.locator('.ld-evidence-image img').getAttribute('src');
    await page.getByLabel('Next evidence frame', { exact: true }).click();
    assert.notEqual(await page.locator('.ld-evidence-image img').getAttribute('src'), firstImage);
    await page.getByLabel('Play evidence frames', { exact: true }).click();
    await expect(page.getByRole('slider', { name: 'Evidence frame', exact: true })).not.toHaveValue('1');
    await page.getByLabel('Pause evidence playback', { exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('.ld-evidence-image img')].every(img => img.complete && img.naturalWidth > 0));
    await page.screenshot({ path: path.join(output, 'evidence-desktop.png') });
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByLabel('Expand activity periods', { exact: true }).click();
    await expect(page.getByRole('dialog').locator('tbody tr')).toHaveCount(3);
    await page.getByRole('dialog').locator('.ld-evidence-link').first().click();
    await expect(page.getByRole('dialog')).toHaveCount(2);
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).toHaveCount(1);
    await page.keyboard.press('Escape');
    await page.getByLabel('Live data activity', { exact: true }).selectOption('pouring');
    await expect(page.locator('.ld-no-results')).toBeVisible();
    await expect(page.locator('.ld-interval')).toHaveCount(0);
    await page.getByRole('button', { name: 'Reset filters', exact: true }).click();
    await page.getByLabel('Live data zone', { exact: true }).selectOption('zones');
    await page.getByLabel('Search activity periods', { exact: true }).fill('Zone 2');
    await expect(page.locator('.ld-table tbody tr')).toHaveCount(1);
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export activity', exact: true }).click();
    const download = await downloadEvent;
    const csv = await fs.readFile(await download.path(), 'utf8');
    assert.equal(csv.split('\r\n').length, 2);
    assert.ok(csv.includes('Zone 2'));
    await page.getByLabel('Dismiss export message', { exact: true }).click();
    await page.getByLabel('Search activity periods', { exact: true }).fill('');
    await page.getByLabel('Sort activity periods', { exact: true }).selectOption('latest');
    await expect(page.locator('.ld-table tbody tr').first()).toContainText('0.25 min');
    for (const [label, width, height] of [['desktop', 1440, 1100], ['tablet', 768, 1024], ['mobile', 390, 844]]) {
      await page.setViewportSize({ width, height });
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.waitForFunction(() => [...document.querySelectorAll('.ex-live-data img')].every(img => img.complete && img.naturalWidth > 0));
      const dimensions = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
      assert.ok(dimensions.scroll <= dimensions.width + 1, `${label} page overflow: ${JSON.stringify(dimensions)}`);
      await page.screenshot({ path: path.join(output, `live-${label}.png`), fullPage: true });
    }
    await page.locator('.ld-evidence-link').first().click();
    await page.screenshot({ path: path.join(output, 'evidence-mobile.png') });
    await page.keyboard.press('Escape');
    await page.getByRole('tab', { name: 'Reports', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Key performance', exact: true })).toBeVisible();
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ result: 'PASS', checks: ['local video loads and plays', 'timeline seeks video', 'decoded video pixels and playhead', 'zone and activity filters', 'search and sort', 'timeline zoom/reset', 'evidence playback and nested dialogs', 'filtered CSV download', 'desktop/tablet/mobile layout', 'local-only data and assets', 'Reports tab'], screenshots: output }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
